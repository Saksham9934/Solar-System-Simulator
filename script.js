const TS = QUALITY.textureSize;

function makeCanvas(w = TS, h = TS/2){
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  return { c, ctx: c.getContext('2d') };
}
function rand(min,max){ return Math.random()*(max-min)+min; }
function pick(arr){ return arr[(Math.random()*arr.length)|0]; }

function toTexture(canvas, colorData = true){
  const tex = new THREE.CanvasTexture(canvas);
  tex.wrapS = THREE.RepeatWrapping;
  tex.anisotropy = 4;
  if (colorData) tex.colorSpace = THREE.SRGBColorSpace;
  tex.needsUpdate = true;
  return tex;
}

/* Mottled rocky/cratered surface (Mercury, Mars) */
function textureRocky(palette){
  const { c, ctx } = makeCanvas();
  ctx.fillStyle = palette[0]; ctx.fillRect(0,0,c.width,c.height);
  for (let i=0;i<420;i++){
    ctx.globalAlpha = rand(0.08,0.32);
    ctx.fillStyle = pick(palette);
    const x = rand(0,c.width), y = rand(0,c.height), r = rand(4, c.width*0.05);
    ctx.beginPath(); ctx.ellipse(x,y,r,r*rand(0.6,1),rand(0,Math.PI),0,Math.PI*2); ctx.fill();
  }
  ctx.globalAlpha = 1;
  // craters
  for (let i=0;i<160;i++){
    const x = rand(0,c.width), y = rand(0,c.height), r = rand(3,22);
    const grad = ctx.createRadialGradient(x,y,0,x,y,r);
    grad.addColorStop(0,'rgba(0,0,0,0.35)');
    grad.addColorStop(0.7,'rgba(0,0,0,0.12)');
    grad.addColorStop(1,'rgba(0,0,0,0)');
    ctx.fillStyle = grad;
    ctx.beginPath(); ctx.arc(x,y,r,0,Math.PI*2); ctx.fill();
    ctx.strokeStyle = 'rgba(255,255,255,0.06)';
    ctx.beginPath(); ctx.arc(x,y,r*1.05,0,Math.PI*2); ctx.stroke();
  }
  return toTexture(c);
}

/* Thick swirling cloud world (Venus) */
function textureVenus(palette){
  const { c, ctx } = makeCanvas();
  const grad = ctx.createLinearGradient(0,0,0,c.height);
  grad.addColorStop(0, palette[2]); grad.addColorStop(1, palette[1]);
  ctx.fillStyle = grad; ctx.fillRect(0,0,c.width,c.height);
  for (let i=0;i<60;i++){
    const y = rand(0,c.height);
    ctx.strokeStyle = pick(palette);
    ctx.globalAlpha = rand(0.06,0.18);
    ctx.lineWidth = rand(4,18);
    ctx.beginPath();
    ctx.moveTo(0, y);
    for (let x=0;x<=c.width;x+=40){
      ctx.lineTo(x, y + Math.sin(x*0.02+i)*14);
    }
    ctx.stroke();
  }
  ctx.globalAlpha = 1;
  return toTexture(c);
}

/* Banded gas / ice giant with optional storm spot */
function textureBanded(palette, { storm=false, turbulence=1 } = {}){
  const { c, ctx } = makeCanvas();
  const bandCount = 18;
  let y = 0;
  const bandH = c.height / bandCount;
  for (let i=0;i<bandCount;i++){
    ctx.fillStyle = pick(palette);
    ctx.fillRect(0, y, c.width, bandH+1);
    y += bandH;
  }
  // horizontal turbulence via sine-warped overlay strips
  for (let i=0;i<70*turbulence;i++){
    const yy = rand(0,c.height);
    ctx.strokeStyle = pick(palette);
    ctx.globalAlpha = rand(0.05,0.16);
    ctx.lineWidth = rand(2,10);
    ctx.beginPath();
    ctx.moveTo(0,yy);
    for (let x=0;x<=c.width;x+=30){
      ctx.lineTo(x, yy + Math.sin(x*0.03+i*3)*10*turbulence);
    }
    ctx.stroke();
  }
  ctx.globalAlpha = 1;
  if (storm){
    const sx = c.width*0.32, sy = c.height*0.62, sr = c.width*0.09;
    const grad = ctx.createRadialGradient(sx,sy,sr*0.1,sx,sy,sr);
    grad.addColorStop(0,'#e2694a'); grad.addColorStop(0.6,'#c85436'); grad.addColorStop(1,'rgba(200,84,54,0)');
    ctx.fillStyle = grad;
    ctx.beginPath(); ctx.ellipse(sx,sy,sr,sr*0.62,0,0,Math.PI*2); ctx.fill();
  }
  return toTexture(c);
}

/* Earth: oceans + continents + polar caps */
function textureEarth(palette){
  const { c, ctx } = makeCanvas();
  ctx.fillStyle = palette[0]; ctx.fillRect(0,0,c.width,c.height);
  // continents
  for (let i=0;i<26;i++){
    ctx.fillStyle = Math.random()>0.3 ? palette[2] : palette[3];
    ctx.globalAlpha = rand(0.55,0.9);
    const cx = rand(0,c.width), cy = rand(c.height*0.12,c.height*0.88);
    ctx.beginPath();
    const pts = 8;
    for (let p=0;p<=pts;p++){
      const a = (p/pts)*Math.PI*2;
      const r = rand(c.width*0.02, c.width*0.075);
      const x = cx + Math.cos(a)*r, y = cy + Math.sin(a)*r*0.7;
      p===0 ? ctx.moveTo(x,y) : ctx.lineTo(x,y);
    }
    ctx.closePath(); ctx.fill();
  }
  ctx.globalAlpha = 1;
  // polar caps
  const capH = c.height*0.09;
  let g1 = ctx.createLinearGradient(0,0,0,capH*1.6);
  g1.addColorStop(0,'rgba(255,255,255,0.95)'); g1.addColorStop(1,'rgba(255,255,255,0)');
  ctx.fillStyle = g1; ctx.fillRect(0,0,c.width,capH*1.6);
  let g2 = ctx.createLinearGradient(0,c.height,0,c.height-capH*1.6);
  g2.addColorStop(0,'rgba(255,255,255,0.95)'); g2.addColorStop(1,'rgba(255,255,255,0)');
  ctx.fillStyle = g2; ctx.fillRect(0,c.height-capH*1.6,c.width,capH*1.6);
  return toTexture(c);
}

