function easeInOutCubic(t){ return t<0.5 ? 4*t*t*t : 1-Math.pow(-2*t+2,3)/2; }

function selectPlanet(key){
  if (key === 'sun'){
    state.selected = 'sun';
    updateNavActive('sun');
    const dir = new THREE.Vector3(0.6,0.35,1).normalize();
    flyTo(dir.multiplyScalar(SUN.radius*4.2), new THREE.Vector3(0,0,0));
    showInfo({ name:'Sun', type:'G-TYPE MAIN-SEQUENCE STAR',
      desc:'The star at the heart of our solar system, containing 99.8% of its total mass.',
      facts:{ diameter:'1,391,000 km', distance:'0 km (center)', moons:'—', day:'~27 Earth days', year:'—', temp:'5,500°C surface' },
      notes:['The Sun fuses roughly 600 million tons of hydrogen into helium every second.',
             'Light from the Sun takes about 8 minutes and 20 seconds to reach Earth.',
             'It accounts for about 99.86% of the total mass of the solar system.'] });
    return;
  }
  const entry = planetMeshes.find(p => p.cfg.key === key);
  if (!entry) return;
  state.selected = key;
  const p = worldPosOf(entry);
  const dist = entry.cfg.radius * 5.5 + 3.5;
  const dir = camera.position.clone().sub(p);
  if (dir.lengthSq() < 0.001) dir.set(1,0.4,1);
  dir.normalize().multiplyScalar(dist);
  dir.y = Math.max(dir.y, dist*0.28);
  flyTo(p.clone().add(dir), p);
  showInfo(entry.cfg);
  updateNavActive(key);
}

