function updateComets(dt, elapsed){
  comets.forEach(c => {
    const a = c.phase + elapsed*c.speed;
    const r = c.a * (1 - c.e*c.e) / (1 + c.e*Math.cos(a));
    const x = Math.cos(a)*r;
    const z = Math.sin(a)*r;
    const y = Math.sin(a*0.7)*r*Math.sin(c.incl)*0.3;
    c.group.position.set(x,y,z);

    c.history.unshift(c.group.position.clone());
    if (c.history.length > c.TRAIL_LEN) c.history.pop();
    const posAttr = c.trail.geometry.attributes.position;
    const colAttr = c.trail.geometry.attributes.color;
    for (let i=0;i<c.TRAIL_LEN;i++){
      const p = c.history[i] || c.history[c.history.length-1] || c.group.position;
      posAttr.setXYZ(i, p.x, p.y, p.z);
      const fade = 1 - i/c.TRAIL_LEN;
      colAttr.setXYZ(i, 0.55*fade+0.1, 0.8*fade+0.1, 1.0*fade+0.2);
    }
    posAttr.needsUpdate = true; colAttr.needsUpdate = true;
  });
}

function updateFlight(dt){
  const f = state.flight;
  if (!f) return;
  f.t += dt / f.duration;
  const t = Math.min(f.t, 1);
  const e = easeInOutCubic(t);
  camera.position.lerpVectors(f.startPos, f.endPos, e);
  controls.target.lerpVectors(f.startTarget, f.endTarget, e);
  if (t >= 1){
    state.flight = null;
    controls.enabled = true;
  }
}

function tick(){
  const dt = Math.min(clock.getDelta(), 0.05);
  const elapsed = clock.elapsedTime;

  if (starMat) starMat.uniforms.uTime.value = elapsed;
  sunMesh.rotation.y += dt*0.02;
  corona.material.rotation += dt*0.01;
  sunParticles.rotation.y += dt*0.015;

  if (state.playing){
    const dSim = dt * state.speed;
    state.simDays += dSim * (365.25/YEAR_SECONDS);

    planetMeshes.forEach(entry => {
      entry.angle += entry.orbitSpeed * dSim;
      entry.orbitAnchor.rotation.y = entry.angle;
      entry.mesh.rotation.y += entry.rotSpeed * dSim * 40;
      if (entry.cloudMesh) entry.cloudMesh.rotation.y += dt*0.01*state.speed;
      entry.moons.forEach(m => {
        m.angle += (Math.PI*2/(YEAR_SECONDS*(m.cfg.orbitPeriodDays/365.25))) * dSim;
        m.anchor.rotation.y = m.angle;
      });
    });
    beltGroup.rotation.y += dt*0.006*state.speed;
    updateComets(dSim, elapsed);
  }

  updateFlight(dt);
  controls.update();
  updateLabels();

  const simDate = document.getElementById('sim-date');
  const y = Math.floor(state.simDays/365.25);
  const d = Math.floor(state.simDays%365.25);
  simDate.textContent = `Y${y} · D${d}`;

  composer.render();
  requestAnimationFrame(tick);
}

